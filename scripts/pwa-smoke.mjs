import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { createHash, X509Certificate } from 'node:crypto';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { connect as connectTls } from 'node:tls';
import { pathToFileURL } from 'node:url';
import { connectCdp } from './cdp.mjs';

// Pin the browser's test-only TLS exception to this server's public key.
// This does not install a certificate or change the system/user trust store.
async function serverSpki(url) {
  return new Promise((resolvePin, reject) => {
    const socket = connectTls({
      host: url.hostname.replace(/^\[|\]$/g, ''), port: Number(url.port || 443),
      rejectUnauthorized: false,
    });
    socket.setTimeout(8000, () => socket.destroy(new Error('HTTPS server did not respond')));
    socket.once('error', reject);
    socket.once('secureConnect', () => {
      try {
        const certificate = new X509Certificate(socket.getPeerCertificate().raw);
        const spki = certificate.publicKey.export({ type: 'spki', format: 'der' });
        resolvePin(createHash('sha256').update(spki).digest('base64'));
      } catch (error) { reject(error); }
      finally { socket.destroy(); }
    });
  });
}

// A worker is a separate CDP target. Page-only offline emulation leaves the
// worker's own fetch() online, so connect to that target as well.
async function workerSession(origin) {
  const targets = await (await fetch('http://127.0.0.1:9341/json/list')).json();
  const target = targets.find(item => item.type === 'service_worker' && item.url === origin + '/sw.js');
  assert.ok(target?.webSocketDebuggerUrl, 'The registered service worker must expose a debugging target');
  const socket = new WebSocket(target.webSocketDebuggerUrl);
  await new Promise((resolveOpen, reject) => {
    socket.addEventListener('open', resolveOpen, { once: true });
    socket.addEventListener('error', reject, { once: true });
  });
  let next = 0;
  const pending = new Map();
  socket.addEventListener('message', ({ data }) => {
    const message = JSON.parse(data);
    const item = pending.get(message.id);
    if (!item) return;
    pending.delete(message.id); clearTimeout(item.timer);
    message.error ? item.reject(new Error(JSON.stringify(message.error))) : item.resolve(message.result);
  });
  return {
    command(method, params = {}) {
      return new Promise((resolveCommand, reject) => {
        const id = ++next;
        const timer = setTimeout(() => { pending.delete(id); reject(new Error(`Worker CDP timeout: ${method}`)); }, 10000);
        pending.set(id, { resolve: resolveCommand, reject, timer });
        socket.send(JSON.stringify({ id, method, params }));
      });
    },
    close() { socket.close(); },
  };
}

export async function pwaSmoke(address) {
  const url = new URL(address);
  assert.equal(url.protocol, 'https:', 'Use the HTTPS URL generated by HeartWire');
  assert.equal(url.username + url.password, '', 'Credentials do not belong in the test URL');
  const pin = await serverSpki(url);
  const profile = resolve('artifacts/edge-pwa-smoke');
  await mkdir(profile, { recursive: true });
  const edge = spawn('C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe', [
    '--headless=new', '--disable-gpu', '--no-first-run', '--no-default-browser-check',
    `--ignore-certificate-errors-spki-list=${pin}`, '--remote-debugging-port=9341',
    `--user-data-dir=${profile}`, 'about:blank',
  ], { windowsHide: true, stdio: 'ignore' });
  let browser;
  let worker;
  try {
    browser = await connectCdp(9341);
    const { command, evaluate, waitFor } = browser;
    await command('Network.enable');
    await command('Network.setCacheDisabled', { cacheDisabled: true });
    await command('Storage.clearDataForOrigin', { origin: url.origin, storageTypes: 'all' });
    await command('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: true });
    const start = new URL('/?mode=mic&lang=en', url);
    await command('Page.navigate', { url: start.href });
    await waitFor(`document.getElementById('connect') && !document.getElementById('connect').disabled`, 15000);
    assert.equal(await evaluate('window.isSecureContext'), true);
    const registration = await evaluate(`navigator.serviceWorker.register('/sw.js', {scope:'/',updateViaCache:'none'}).then(registration => ({scope:registration.scope})).catch(error => ({error:error.message}))`);
    assert.equal(registration.error, undefined, `Service worker failed: ${registration.error}`);
    assert.equal(registration.scope, url.origin + '/');
    await waitFor('navigator.serviceWorker.controller !== null', 15000);
    assert.equal(await evaluate('document.documentElement.lang'), 'en');
    assert.equal(await evaluate(`document.getElementById('connection-title').textContent`), 'Disconnected');
    assert.equal(await evaluate(`localStorage.getItem('heartwire.language')`), 'en');
    const liveMode = await evaluate(`fetch('/status', {cache:'no-store'}).then(response => response.json()).then(state => ({mode:state.mode, running:state.running}))`);
    assert.equal(liveMode.running, true, 'Start HeartWire before running this test');
    assert.equal(await evaluate('mode'), liveMode.mode, 'The live PC mode overrides an old Home Screen URL');

    const appManifest = await command('Page.getAppManifest');
    assert.deepEqual(appManifest.errors.filter(error => error.critical), [], 'Browser manifest errors');
    const manifest = JSON.parse(appManifest.data);
    assert.equal(manifest.name, 'HeartWire');
    assert.equal(manifest.display, 'standalone');
    assert.equal(manifest.start_url, '/');
    assert.equal(manifest.id, '/');
    const iconSizes = await evaluate(`(async () => {
      const manifest = await (await fetch('/manifest.webmanifest')).json();
      return Promise.all([...manifest.icons, {src:'/icons/apple-touch-icon.png',sizes:'180x180'}].map(async icon => {
        const image = new Image(); image.src = icon.src; await image.decode();
        return { expected:icon.sizes, actual:image.naturalWidth+'x'+image.naturalHeight };
      }));
    })()`);
    for (const icon of iconSizes) assert.equal(icon.actual, icon.expected, 'A PWA icon did not decode at its declared size');

    // Exercise live API requests without allocating a WebRTC peer or microphone.
    await evaluate(`Promise.all(['/offer','/mic-offer'].map(path => fetch(path, {method:'POST',headers:{'Content-Type':'application/json'},body:'invalid-json'})))`);
    const cachedPaths = await evaluate(`(async () => {
      const paths = [];
      for (const name of await caches.keys()) {
        if (!name.startsWith('heartwire-shell-')) continue;
        for (const request of await (await caches.open(name)).keys()) {
          const url = new URL(request.url); paths.push(url.pathname + url.search);
        }
      }
      return paths.sort();
    })()`);
    assert.ok(cachedPaths.includes('/offline.html'));
    assert.ok(cachedPaths.includes('/icons/apple-touch-icon.png'));
    for (const path of cachedPaths) {
      assert.ok(!path.includes('?'), `Cached a private query: ${path}`);
      assert.ok(!['/', '/status', '/offer', '/mic-offer'].includes(path), `Cached a live API: ${path}`);
    }

    await evaluate(`document.getElementById('mobile-tab-settings').click();document.getElementById('language-select').value='pt-BR';document.getElementById('language-select').dispatchEvent(new Event('change'))`);
    assert.equal(await evaluate(`localStorage.getItem('heartwire.language')`), 'pt-BR');
    assert.equal(await evaluate(`document.getElementById('mobile-tab-settings').textContent`), 'Ajustes');
    await evaluate(`document.getElementById('language-select').value='en';document.getElementById('language-select').dispatchEvent(new Event('change'))`);
    await command('Page.navigate', { url: url.origin + '/' });
    await waitFor(`document.getElementById('connect') && !document.getElementById('connect').disabled && navigator.serviceWorker.controller !== null`);
    assert.equal(await evaluate('document.documentElement.lang'), 'en', 'Installed start_url must retain the selected language');
    assert.equal(await evaluate('mode'), liveMode.mode);
    await waitFor(`Array.from(document.images).every(image => image.complete && image.naturalWidth > 0)`);
    const online = await command('Page.captureScreenshot', { format: 'png' });
    await writeFile('artifacts/pwa-online.png', Buffer.from(online.data, 'base64'));

    worker = await workerSession(url.origin);
    await worker.command('Network.enable');
    await worker.command('Network.setCacheDisabled', { cacheDisabled: true });
    await worker.command('Network.emulateNetworkConditions', { offline: true, latency: 0, downloadThroughput: 0, uploadThroughput: 0 });
    await command('Network.emulateNetworkConditions', { offline: true, latency: 0, downloadThroughput: 0, uploadThroughput: 0 });
    await command('Page.navigate', { url: url.origin + '/' });
    await waitFor(`document.getElementById('offline-title')?.textContent === 'PC unavailable'`, 15000);
    assert.equal(await evaluate(`document.getElementById('connect') === null && document.getElementById('connection') === null`), true, 'Offline page must never expose a connected state');
    await waitFor(`Array.from(document.images).every(image => image.complete && image.naturalWidth > 0)`);
    assert.equal(await evaluate(`fetch('/status').then(() => false).catch(() => true)`), true, 'Offline API must fail rather than return a cached peer count');
    const offline = await command('Page.captureScreenshot', { format: 'png' });
    await writeFile('artifacts/pwa-offline.png', Buffer.from(offline.data, 'base64'));

    await worker.command('Network.emulateNetworkConditions', { offline: false, latency: 0, downloadThroughput: -1, uploadThroughput: -1 });
    await command('Network.emulateNetworkConditions', { offline: false, latency: 0, downloadThroughput: -1, uploadThroughput: -1 });
    await command('Page.navigate', { url: url.origin + '/' });
    await waitFor(`document.getElementById('connect') && !document.getElementById('connect').disabled`);
    assert.equal(await evaluate(`document.getElementById('connection-title').textContent`), 'Disconnected');
    assert.deepEqual(browser.exceptions, [], 'PWA has uncaught browser errors');
    console.log(`PWA HTTPS: SW ativo, manifest/ícones, PT-BR/EN, modo ${liveMode.mode}, cache público, offline e recuperação OK`);
  } catch (error) {
    if (browser) {
      const diagnostic = await browser.evaluate(`({url:location.href,readyState:document.readyState,title:document.title,text:document.body?.innerText?.slice(0,5000),online:navigator.onLine,worker:navigator.serviceWorker?.controller?.scriptURL || null})`).catch(failure => ({diagnosticError:failure.message}));
      diagnostic.targets = (await browser.command('Target.getTargets').catch(() => ({}))).targetInfos;
      await writeFile('artifacts/pwa-failure.json', JSON.stringify(diagnostic, null, 2));
      const screenshot = await browser.command('Page.captureScreenshot', {format:'png'}).catch(() => null);
      if (screenshot) await writeFile('artifacts/pwa-failure.png', Buffer.from(screenshot.data, 'base64'));
      console.error('PWA diagnostic: artifacts/pwa-failure.json / pwa-failure.png');
    }
    throw error;
  } finally {
    worker?.close();
    if (browser) await browser.command('Browser.close').catch(() => {});
    browser?.close();
    edge.kill();
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  if (!process.argv[2]) throw new Error('Uso: node scripts/pwa-smoke.mjs https://IP:PORTA');
  await pwaSmoke(process.argv[2]);
}
